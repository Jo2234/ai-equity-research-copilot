def test_row_contract_contains_only_source_structure_and_exact_excerpts():
    from dataclasses import asdict

    text = "(In millions)\n2031 2030\nCash (100) 90\nUnknown — –"
    rows = financial_table_facts(text)
    assert len(rows) == 1  # An entirely missing row is not invented as zero.
    assert set(asdict(rows[0])) == {"label", "source_excerpt", "header_span", "row_span", "context_span"}
    assert rows[0].source_excerpt.endswith("Cash (100) 90")
    assert text[slice(*rows[0].header_span)] in rows[0].source_excerpt
    assert text[slice(*rows[0].row_span)] in rows[0].source_excerpt
