def test_explicit_capital_approach_groups_preserve_dates_and_percent_cells():
    text = """Standardized Advanced
(in millions, except ratios) March 31, 2031
December 31, 2030
Capital ratio requirements (a)
March 31, 2031
December 31, 2030
Capital ratio requirements (a)
Risk-based capital metrics:
CET1 capital 290000 280000 290000 280000
CET1 capital ratio 14.2 % 14.5 % 11.4 % 14.0 % 14.1 % 11.4 %
Tier 1 capital ratio 15.3 15.4 13.0 15.2 15.3 13.0
"""
    facts = financial_table_facts(text)
    assert len(facts) == 2  # Incomplete amount row is still rejected.
    assert "Standardized Advanced" in facts[0].source_excerpt
    assert facts[0].source_excerpt.count("March 31, 2031") == 2
    assert facts[0].source_excerpt.count("December 31, 2030") == 2
    assert facts[0].source_excerpt.count("Capital ratio requirements (a)") == 2
    assert facts[0].source_excerpt.endswith("CET1 capital ratio 14.2 % 14.5 % 11.4 % 14.0 % 14.1 % 11.4 %")
    assert facts[1].source_excerpt.endswith("Tier 1 capital ratio 15.3 15.4 13.0 15.2 15.3 13.0")
    assert "%" not in facts[1].source_excerpt


