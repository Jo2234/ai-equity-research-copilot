from ai_equity_research_copilot_backend.financial_tables import financial_table_facts


def test_vertical_segment_table_keeps_period_scale_and_source_context():
    text = """SEGMENT RESULTS OF OPERATIONS
(In millions, except percentages)
2031
2030
Percentage
Change
Enterprise Services
Revenue
$ 124,810
$ 105,120
19%
Operating income
$ 14,121
$ 12,140
16%
Consumer Devices
Revenue
$ 36,123
$ 31,912
13%
"""
    facts = financial_table_facts(text)
    assert len(facts) == 3
    first = facts[0]
    assert first.label == "Enterprise Services: Revenue"
    assert text[slice(*first.row_span)] == "Revenue\n$ 124,810\n$ 105,120\n19%"
    assert "2031\n2030\nPercentage\nChange" in first.source_excerpt
    assert "(In millions, except percentages)" in first.source_excerpt
    assert text[slice(*first.context_span)] == "Enterprise Services"
    assert facts[-1].label == "Consumer Devices: Revenue"


